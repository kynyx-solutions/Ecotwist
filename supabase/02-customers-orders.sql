create table if not exists public.customers (
  id              uuid primary key default gen_random_uuid(),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  name            text not null,
  company         text not null default '',
  email           text not null default '',
  phone           text not null default '',
  gstin           text not null default '',
  address         text not null default '',
  city            text not null default '',
  notes           text not null default '',
  source_lead_id  uuid references public.leads (id) on delete set null
);

create index if not exists customers_created_at_idx on public.customers (created_at desc);

create table if not exists public.orders (
  id                uuid primary key default gen_random_uuid(),
  number            bigint generated by default as identity (start with 1001) unique,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  customer_id       uuid not null references public.customers (id) on delete restrict,
  status            text not null default 'quote'
                    check (status in ('quote', 'confirmed', 'in_production', 'dispatched', 'delivered', 'cancelled')),
  occasion          text not null default '',
  -- [{ "product": "...", "quantity": 100, "unit_price": 450 }]
  items             jsonb not null default '[]'::jsonb,
  gst_rate          numeric(5, 2) not null default 18,
  total_amount      numeric(12, 2) not null default 0,  -- incl. GST
  advance_paid      numeric(12, 2) not null default 0,
  delivery_date     date,
  delivery_address  text not null default '',
  notes             text not null default '',
  created_by        uuid references public.profiles (id) on delete set null
);

create index if not exists orders_customer_idx on public.orders (customer_id, created_at desc);
create index if not exists orders_status_idx on public.orders (status);

drop trigger if exists customers_touch on public.customers;
create trigger customers_touch before update on public.customers
  for each row execute function public.touch_updated_at();

drop trigger if exists orders_touch on public.orders;
create trigger orders_touch before update on public.orders
  for each row execute function public.touch_updated_at();

alter table public.customers enable row level security;
alter table public.orders    enable row level security;

drop policy if exists "staff read customers" on public.customers;
create policy "staff read customers" on public.customers for select using (public.is_staff());
drop policy if exists "staff add customers" on public.customers;
create policy "staff add customers" on public.customers for insert with check (public.is_staff());
drop policy if exists "staff update customers" on public.customers;
create policy "staff update customers" on public.customers for update using (public.is_staff()) with check (public.is_staff());
drop policy if exists "admins delete customers" on public.customers;
create policy "admins delete customers" on public.customers for delete using (public.is_admin());

drop policy if exists "staff read orders" on public.orders;
create policy "staff read orders" on public.orders for select using (public.is_staff());
drop policy if exists "staff add orders" on public.orders;
create policy "staff add orders" on public.orders for insert with check (public.is_staff());
drop policy if exists "staff update orders" on public.orders;
create policy "staff update orders" on public.orders for update using (public.is_staff()) with check (public.is_staff());
drop policy if exists "admins delete orders" on public.orders;
create policy "admins delete orders" on public.orders for delete using (public.is_admin());
